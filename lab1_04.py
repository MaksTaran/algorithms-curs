# Задача 4. Даны два ненулевых числа.
# Найти сумму, разность, произведение и частное их квадратов.

a = float(input("a = "))
b = float(input("b = "))

a2 = a * a             # квадрат первого числа
b2 = b * b             # квадрат второго числа

print("Сумма квадратов:", a2 + b2)
print("Разность квадратов:", a2 - b2)
print("Произведение квадратов:", a2 * b2)
print("Частное квадратов:", a2 / b2)   # b ≠ 0 по условию