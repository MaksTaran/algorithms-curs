# Задача 5. Даны два ненулевых числа.
# Найти сумму, разность, произведение и частное их модулей.

a = float(input("a = "))
b = float(input("b = "))

aa = abs(a)            # модуль первого числа
bb = abs(b)            # модуль второго числа

print("Сумма модулей:", aa + bb)
print("Разность модулей:", aa - bb)
print("Произведение модулей:", aa * bb)
print("Частное модулей:", aa / bb)    # b ≠ 0 по условию