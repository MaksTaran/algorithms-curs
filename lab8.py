# Лабораторная 8. Сортировка вставками.
def insertion_sort(a):
    n = len(a)
    for i in range(1, n):              # i — индекс вставляемого элемента
        key = a[i]                     # запоминаем текущий элемент
        j = i - 1                      # идём по отсортированной части справа налево
        # сдвигаем все элементы больше key на одну позицию вправо
        while j >= 0 and a[j] > key:
            a[j + 1] = a[j]
            j -= 1
        a[j + 1] = key                 # вставляем key на освободившееся место
     # печать после прохода: показываем, где заканчивается отсортированная часть
        sorted_part = a[:i + 1]
        rest_part   = a[i + 1:]
        print(f"Проход {i}: key={key:>3}  →  {sorted_part} | {rest_part}")
    return a

n = int(input("Размер массива: "))
a = list(map(int, input(f"Введите {n} элементов через пробел: ").split()))

print("Исходный массив:", a)
insertion_sort(a)
print("Отсортированный массив:", a)