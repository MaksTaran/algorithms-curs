# Задача 9. Число 100–999 → «двести пятьдесят шесть» и т. п.

n = int(input("Число (100-999): "))

hundreds   = ["", "сто", "двести", "триста", "четыреста",
              "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]
tens_w     = ["", "", "двадцать", "тридцать", "сорок",
              "пятьдесят", "шестьдесят", "семьдесят",
              "восемьдесят", "девяносто"]
ones       = ["", "один", "два", "три", "четыре", "пять",
              "шесть", "семь", "восемь", "девять"]
teens      = ["десять", "одиннадцать", "двенадцать", "тринадцать",
              "четырнадцать", "пятнадцать", "шестнадцать",
              "семнадцать", "восемнадцать", "девятнадцать"]

h   = n // 100         # сотни
rem = n % 100          # остаток (0..99)
parts = [hundreds[h]]

if 10 <= rem <= 19:                     # 10..19 — одним словом
    parts.append(teens[rem - 10])
elif rem >= 20:                         # 20..99 — десятки + единицы
    parts.append(tens_w[rem // 10])
    if rem % 10 != 0:                   # если есть ненулевые единицы
        parts.append(ones[rem % 10])
elif 1 <= rem <= 9:                     # 1..9 — просто единицы
    parts.append(ones[rem])

print(" ".join(parts))