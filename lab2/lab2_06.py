# Задача 6. Строка-описание числа 1–999: чётность + разрядность.

n = int(input("n (1-999) = "))

# чётность
if n % 2 == 0:
    parity = "четное"
else:
    parity = "нечетное"

# разрядность по величине числа
if n < 10:
    digits = "однозначное"
elif n < 100:
    digits = "двузначное"
else:
    digits = "трехзначное"

print(parity, digits, "число")