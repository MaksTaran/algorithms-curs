# Задача 5. Строка-описание целого числа: знак + чётность.

n = int(input("n = "))

if n == 0:
    print("нулевое число")
else:
    # определяем знак
    if n > 0:
        sign = "положительное"
    else:
        sign = "отрицательное"

    # определяем чётность: остаток от деления на 2
    if n % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"

    print(sign, parity, "число")