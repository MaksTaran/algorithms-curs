# Задача 8. Число 10–40 → «восемнадцать учебных заданий» и т. п.

n = int(input("Количество заданий (10-40): "))

# --- словесная запись числа ---
ones   = ["", "одно", "два", "три", "четыре", "пять",
          "шесть", "семь", "восемь", "девять"]
teens  = ["десять", "одиннадцать", "двенадцать", "тринадцать",
          "четырнадцать", "пятнадцать", "шестнадцать",
          "семнадцать", "восемнадцать", "девятнадцать"]
tens_w = ["", "", "двадцать", "тридцать", "сорок"]

if n < 20:
    num_word = teens[n - 10]                # 10..19
else:
    t = n // 10                              # десятки
    o = n % 10                               # единицы
    if o == 0:
        num_word = tens_w[t]                 # ровно 20, 30, 40
    else:
        num_word = tens_w[t] + " " + ones[o] # 21..39

# --- форма слова «задание» ---
if n in (11, 12, 13, 14):
    noun = "учебных заданий"                 # исключения-подростки
elif n % 10 == 1:
    noun = "учебное задание"                 # 21, 31
elif n % 10 in (2, 3, 4):
    noun = "учебных задания"                 # 22–24, 32–34
else:
    noun = "учебных заданий"                 # 10, 15–20, 25–30, 35–40

print(num_word, noun)