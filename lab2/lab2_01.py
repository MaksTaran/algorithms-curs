# Задача 1. Если A ≠ B — присвоить обеим переменным большее значение.
# Если A == B — присвоить обеим нули.

A = int(input("A = "))
B = int(input("B = "))

if A != B:              # значения не равны
    m = max(A, B)       # находим большее
    A = m               # присваиваем обеим
    B = m
else:                   # значения равны
    A = 0
    B = 0

print("A =", A)
print("B =", B)