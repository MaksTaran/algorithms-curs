# Задача 9. Даны две противоположные вершины прямоугольника,
# стороны параллельны осям. Найти периметр и площадь.
# Длины сторон — это модули разностей координат по X и по Y.

x1 = float(input("x1 = "))
y1 = float(input("y1 = "))
x2 = float(input("x2 = "))
y2 = float(input("y2 = "))

width  = abs(x2 - x1)   # длина стороны вдоль оси X
height = abs(y2 - y1)   # длина стороны вдоль оси Y

P = 2 * (width + height)   # периметр
S = width * height         # площадь

print("Периметр P =", P)
print("Площадь S =", S)