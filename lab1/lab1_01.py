# Лабораторная работа 1. Линейные алгоритмы.
# Задача 1. Даны стороны прямоугольника a и b.
# Найти площадь S = a·b и периметр P = 2·(a + b).
a = float(input("a = "))
b = float(input("b = "))
S = a * b                    # площадь
P = 2 * (a + b)              # периметр
print("Площадь S =", S)
print("Периметр P =", P)