# Задача 9. Номер последнего локального максимума.
# Локальный максимум — элемент больше ЛЮБОГО из соседей (то есть обоих).
# Первый и последний элементы не могут быть локальными максимумами (у них один сосед).

N = int(input("N = "))
a = list(map(int, input(f"Введите {N} элементов: ").split()))

last_index = -1          # -1 означает «не найден»
for i in range(1, N - 1):
    if a[i] > a[i - 1] and a[i] > a[i + 1]:
        last_index = i   # перезаписываем — цикл идёт по возрастанию, в конце останется последний

if last_index == -1:
    print("Локальных максимумов нет")
else:
    print("Номер последнего локального максимума:", last_index + 1)   # +1 → 1-based