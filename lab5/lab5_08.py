# Задача 8. Минимум среди элементов с чётными номерами: A2, A4, A6, ...
# Чётные номера (1-based) = индексы 1, 3, 5, ...

N = int(input("N = "))
a = list(map(int, input(f"Введите {N} элементов: ").split()))

# срез a[1::2] — с индекса 1 через один: a[1], a[3], a[5], ...
even_pos = a[1::2]
print("Минимум =", min(even_pos))