# Задача 5. Сначала элементы с НЕЧЁТНЫМИ номерами (1,3,5,...) — по возрастанию,
# затем с ЧЁТНЫМИ номерами (2,4,6,...) — по убыванию.
# Внимание: «номер» по заданию с 1, а в Python индекс с 0.
# Нечётные номера = индексы 0, 2, 4, ...   Чётные номера = индексы 1, 3, 5, ...

N = int(input("N = "))
a = list(map(int, input(f"Введите {N} элементов: ").split()))

# нечётные НОМЕРА → чётные индексы (0, 2, 4, ...)
for i in range(0, N, 2):
    print(a[i], end=" ")
# чётные НОМЕРА → нечётные индексы, в порядке убывания номера
for i in range(N - 1, 0, -1):
    if i % 2 == 1:
        print(a[i], end=" ")
print()