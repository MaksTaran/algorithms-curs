# Задача 8. Рекурсивно подсчитать количество цифр в числе.

def count_digits(n):
    n = abs(n)               # на случай отрицательного числа
    if n < 10:               # базовый случай: одна цифра
        return 1
    return 1 + count_digits(n // 10)   # отбрасываем последнюю цифру

n = int(input("n = "))
print("Количество цифр:", count_digits(n))