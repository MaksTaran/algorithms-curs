# Задача 9. Вклад 1000 руб., +P% в месяц. Через сколько месяцев > 1100?

P = float(input("P (0 < P < 25) = "))

S = 1000.0                 # текущая сумма
K = 0                      # счётчик месяцев
while S <= 1100:           # пока не превысили 1100
    S = S + S * P / 100    # прирост за месяц = S * P%
    K += 1

print("Месяцев:", K)
print("Итоговый размер вклада:", round(S, 2))