# Задача 7. A > B. Найти длину незанятой части A после укладки
# максимального количества отрезков B. Без умножения и деления.

A = int(input("A = "))
B = int(input("B = "))

rest = A
while rest >= B:           # пока можем отложить ещё один B
    rest -= B              # «вычитаем» отрезок B

print("Незанятая часть =", rest)