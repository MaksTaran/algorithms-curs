# Задача 3. N > 0. N² = 1 + 3 + 5 + ... + (2N-1).
# После каждого слагаемого выводить текущую сумму.

N = int(input("N = "))

total = 0
for i in range(1, N + 1):
    term = 2 * i - 1          # i-е нечётное число: 1, 3, 5
    total += term             # добавляем к сумме
    print(f"После {i}-го слагаемого ({term}): сумма = {total}")

print("Квадрат:", total)