# Задача 1. Цена 1 кг конфет. Вывести стоимость 0.1, 0.2, ..., 1 кг.

price = float(input("Цена 1 кг: "))

# Шаг 0.1 — но float копит погрешность (0.1+0.1+... ≠ ровно 1).
# Надёжнее идти по целым «десятым»: 1, 2, ..., 10, а потом делить на 10.
for i in range(1, 11):
    weight = i / 10          # 0.1, 0.2, ..., 1.0
    cost = price * weight    # стоимость порции
    print(f"{weight:.1f} кг = {cost:.2f} руб.")